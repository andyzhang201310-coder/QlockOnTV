def self_check(items):
    for q in items:
        assert q['subject'] in ('语文', '数学', '英语'), q
        assert isinstance(q['grade'], int) and 1 <= q['grade'] <= 6, q
        assert q['answer'] == 0, q
        assert len(q['options']) == 4 and len(set(q['options'])) == 4, q
        assert all(isinstance(o, str) and o.strip() for o in q['options']), q
        assert q['q'] and len(q['q']) < 120, q
        assert q['id'].startswith('ext-'), q
    assert len(set(x['id'] for x in items)) == len(items)


def apply_to_bank(items, path):
    with io.open(path, 'r', encoding='utf-8') as f:
        text = f.read()
    orig = json.loads(text)
    old_qs = orig['questions']

    # 1) note 末尾追加一句（原文一字不改）
    note_add = (' v%s 追加 %d 题：语文为统编版 1-6 年级古诗文作者、朝代与出处，'
                '数学为图形公式、和差 / 和倍 / 差倍、等差数列、追及、相遇等应用题；'
                '原有 %d 题逐字未改，合计 %d 题。'
                % (orig['version'] + 1, len(items), len(old_qs), len(old_qs) + len(items)))
    m = re.search(r'("note": "[^\n]*?)(",\n  "questions")', text)
    assert m, 'note 行定位失败'
    text = text[:m.start(1)] + m.group(1) + note_add + m.group(2) + text[m.end(2):]

    # 2) version + 1
    old_ver = '"version": %d,' % orig['version']
    assert text.count(old_ver) == 1, 'version 行不唯一'
    text = text.replace(old_ver, '"version": %d,' % (orig['version'] + 1), 1)

    # 3) 在 questions 数组末尾文本追加（不重新序列化原有题目）
    end = text.rfind('\n  ]')
    assert end > 0, 'questions 数组结尾定位失败'
    chunks = []
    for q in items:
        block = json.dumps(q, ensure_ascii=False, indent=2)
        chunks.append('\n'.join('    ' + ln for ln in block.split('\n')))
    text = text[:end] + ',\n' + ',\n'.join(chunks) + text[end:]

    # 4) 全量校验
    merged = json.loads(text)
    assert merged['version'] == orig['version'] + 1
    assert merged['name'] == orig['name']
    assert merged['note'].startswith(orig['note'])
    assert len(merged['questions']) == len(old_qs) + len(items)
    assert merged['questions'][:len(old_qs)] == old_qs, '原有题目被改动！'
    assert merged['questions'][len(old_qs):] == items
    assert set(merged.keys()) == set(orig.keys())

    tmp = path + '.tmp'
    with io.open(tmp, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    os.replace(tmp, path)
    return orig['version'] + 1, len(old_qs), len(merged['questions'])


def main():
    with io.open(BANK, 'r', encoding='utf-8') as f:
        existing = json.load(f)['questions']
    b = build(existing)
    self_check(b.items)
    with io.open(EXTRA, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(b.items, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print('新增 %d 题（语文 %d / 数学 %d / 英语 %d），与现有题干重复而跳过 %d 题'
          % (len(b.items), b.n['语文'], b.n['数学'], b.n['英语'], b.dup))
    by_grade = {}
    for q in b.items:
        key = (q['subject'], q['grade'])
        by_grade[key] = by_grade.get(key, 0) + 1
    for k in sorted(by_grade):
        print('  %s %d 年级: %d' % (k[0], k[1], by_grade[k]))
    print('占位干扰项: %d' % len(b.placeholder))
    for q in b.placeholder[:10]:
        print('  ! ' + q)
    print('新题清单: %s' % EXTRA)

    if '--apply' in sys.argv:
        ver, before, after = apply_to_bank(b.items, BANK)
        print('已写入 %s：version %d，题量 %d -> %d' % (BANK, ver, before, after))
    else:
        print('（预览模式；加 --apply 才写入内置题库）')


if __name__ == '__main__':
    main()
