def fmt(v):
    if isinstance(v, str):
        return v
    if isinstance(v, int):
        return str(v)
    f = round(float(v), 6)
    if abs(f - round(f)) < 1e-9:
        return str(int(round(f)))
    return ("%.6f" % f).rstrip('0').rstrip('.')


class Builder(object):
    def __init__(self, existing_questions):
        self.items = []
        self.seen_q = set(q['q'] for q in existing_questions)
        self.seen_id = set(q['id'] for q in existing_questions)
        self.dup = 0
        self.placeholder = []
        self.n = {'语文': 0, '数学': 0, '英语': 0}

    def add(self, subject, grade, q, correct, wrongs):
        q = q.strip()
        if not q or q in self.seen_q:
            self.dup += 1
            return None
        correct = fmt(correct)
        opts = [correct]
        for w in wrongs:
            s = fmt(w)
            if s and s not in opts:
                opts.append(s)
        k = 1
        while len(opts) < 4:
            try:
                s = fmt(float(correct) + k)
            except (TypeError, ValueError):
                s = ['以上都不对', '条件不足', '无法确定', '题目信息不够'][(k - 1) % 4]
            if s not in opts:
                opts.append(s)
            k += 1
            if k > 12:
                raise ValueError('凑不齐 4 个不同选项：' + q)
        if any(x.startswith(('以上都不对', '条件不足', '无法确定', '题目信息不够')) for x in opts):
            self.placeholder.append(q)
        if len(opts) != 4 or len(set(opts)) != 4:
            raise ValueError('选项不唯一：%s -> %s' % (q, opts))
        self.seen_q.add(q)
        self.n[subject] += 1
        prefix = {'语文': 'ext-chinese', '数学': 'ext-math', '英语': 'ext-english'}[subject]
        idx = '%s-%04d' % (prefix, self.n[subject])
        if idx in self.seen_id:
            raise ValueError('id 冲突 ' + idx)
        self.seen_id.add(idx)
        item = {'subject': subject, 'grade': grade, 'q': q,
                'options': opts, 'answer': 0, 'id': idx}
        self.items.append(item)
        return item

    def concept(self, grade, q, correct, wrongs):
        return self.add('数学', grade, q, correct, wrongs)

    def numeric(self, grade, q, correct, wrongs):
        return self.add('数学', grade, q, correct, wrongs)


def pick(pool, correct, count=3):
    """从池里取 count 个不等于正确答案、互不相同的干扰项"""
    out = []
    for x in pool:
        if x != correct and x not in out:
            out.append(x)
        if len(out) == count:
            break
    return out


def build_chinese(b):
    authors = sorted(set(p[1] for p in POEMS if p[1]))
    titles = [p[0] for p in POEMS]
