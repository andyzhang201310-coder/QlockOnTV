    for i, (title, author, dynasty, grade, line) in enumerate(POEMS):
        if author:
            wrong = [a for a in pick(authors[i % len(authors):] + authors[:i % len(authors)], author)]
            b.add('语文', grade, '《%s》的作者是谁？' % title, author, wrong)
