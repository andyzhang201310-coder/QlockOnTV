    for i, (title, author, dynasty, grade, line) in enumerate(POEMS):
        if not author or i % 3 != 0:
            continue
        pool = authors[i % len(authors):] + authors[:i % len(authors)]
        b.add('语文', grade, '「%s」这句诗的作者是谁？' % line, author, pick(pool, author))

    # 文言文出处 / 年代
    for i, (title, book, era, grade, line) in enumerate(CLASSICS):
        pool = BOOKS[i % len(BOOKS):] + BOOKS[:i % len(BOOKS)]
        if book in BOOKS:
            b.add('语文', grade, '课文《%s》选自哪部书？' % title, book, pick(pool, book))
        else:
            b.add('语文', grade, '课文《%s》的作者是谁？' % title, book,
                  pick(['苏轼', '韩愈', '柳宗元', '欧阳修', '王安石'], book))
        b.add('语文', grade, '「%s」出自哪篇课文？' % line, '《%s》' % title,
              [('《%s》' % c[0]) for c in pick([c[0] for c in CLASSICS[i + 1:] + CLASSICS[:i]], title)])
        b.add('语文', grade, '课文《%s》的故事出自哪个时期？' % title, era,
              pick(era and (DYNASTIES[i % len(DYNASTIES):] + DYNASTIES[:i % len(DYNASTIES)]) or DYNASTIES, era))

    for grade, q, correct, wrongs in LITERATURE:
        b.add('语文', grade, q, correct, wrongs)
    return b


